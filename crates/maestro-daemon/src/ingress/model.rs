//! Canonical key semantics with immutable transport evidence.

use maestro_protocol::frames::{
    ClientInputEvent, ClientKeyCode, ClientKeyKind, ClientKeySource, KeyModifiers,
};
pub use maestro_protocol::shared::WindowsKeyRecord;

/// Native scan code together with its enhanced-key bit.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct PhysicalKeyId(u32);

/// Physical identity when available, otherwise the semantic key code.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum KeyIdentity {
    /// Native scan identity.
    Physical(PhysicalKeyId),
    /// Semantic identity for keys without native scan evidence.
    Semantic(ClientKeyCode),
}

/// Derive scan identity without modifying the native record.
fn physical_key_id(record: WindowsKeyRecord) -> Option<PhysicalKeyId> {
    (record.virtual_scan_code != 0).then(|| {
        PhysicalKeyId(
            u32::from(record.virtual_scan_code)
                | (u32::from(record.control_key_state & 0x0100 != 0) << 16),
        )
    })
}

/// Canonical key fields and owned source evidence.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TerminalKey {
    /// Semantic key code.
    pub code: ClientKeyCode,
    /// Protocol modifier bits.
    pub modifiers: u8,
    /// Canonical key phase.
    pub kind: ClientKeyKind,
    /// Grouped repetition count.
    pub repeat_count: u16,
    /// Alternate shifted code point, not represented on the wire.
    pub shifted_codepoint: Option<u32>,
    /// Text generated by this key.
    pub generated_text: Option<String>,
    /// Original transport evidence, independent of canonical phase.
    source: ClientKeySource,
}

impl TerminalKey {
    /// Construct a synthesized press with repetition count one.
    #[must_use]
    pub fn new(code: ClientKeyCode, modifiers: u8) -> Self {
        Self {
            code,
            modifiers,
            kind: ClientKeyKind::Press,
            repeat_count: 1,
            shifted_codepoint: None,
            generated_text: None,
            source: ClientKeySource::Synthesized,
        }
    }

    /// Set the canonical phase, clearing text and grouped repetition on release.
    #[must_use]
    pub fn with_kind(mut self, kind: ClientKeyKind) -> Self {
        self.kind = kind;
        if kind == ClientKeyKind::Release {
            self.generated_text = None;
            self.repeat_count = 1;
        }
        self
    }

    /// Set grouped repetition to at least one, or one on a release.
    #[must_use]
    pub fn with_repeat_count(mut self, repeat_count: u16) -> Self {
        self.repeat_count = if self.kind == ClientKeyKind::Release {
            1
        } else {
            repeat_count.max(1)
        };
        self
    }

    /// Set generated text, discarding it on a release.
    #[must_use]
    pub fn with_generated_text(mut self, text: Option<String>) -> Self {
        self.generated_text = if self.kind == ClientKeyKind::Release {
            None
        } else {
            text
        };
        self
    }

    /// Infer character text for an unmodified or uppercase Shift press.
    #[must_use]
    pub fn with_text_commit(mut self) -> Self {
        if self.kind == ClientKeyKind::Press
            && let ClientKeyCode::Char(ch) = self.code
            && (self.modifiers == KeyModifiers::NONE
                || (ch.is_uppercase() && self.modifiers == KeyModifiers::SHIFT))
        {
            self.generated_text = Some(ch.to_string());
        }
        self
    }

    /// Replace canonical modifier bits.
    #[must_use]
    pub fn with_modifiers(mut self, modifiers: u8) -> Self {
        self.modifiers = modifiers;
        self
    }

    /// Retain an alternate shifted code point locally.
    #[must_use]
    pub fn with_shifted_codepoint(mut self, shifted_codepoint: u32) -> Self {
        self.shifted_codepoint = Some(shifted_codepoint);
        self
    }

    /// Borrow raw bytes only when the source is VT input.
    #[must_use]
    pub fn vt_bytes(&self) -> Option<&[u8]> {
        match &self.source {
            ClientKeySource::Vt { bytes } => Some(bytes),
            _ => None,
        }
    }

    /// Copy semantic fields into a synthesized, count-one key view.
    #[must_use]
    pub fn as_key_event(&self) -> ClientInputEvent {
        ClientInputEvent::Key {
            code: self.code.clone(),
            modifiers: self.modifiers,
            kind: self.kind,
            repeat_count: 1,
            generated_text: None,
            source: ClientKeySource::Synthesized,
        }
    }

    /// Replace source evidence with a native record and normalize its count.
    #[must_use]
    pub fn with_windows_record(mut self, record: WindowsKeyRecord) -> Self {
        self.source = ClientKeySource::WindowsConsole { record };
        self.with_repeat_count(record.repeat_count)
    }

    /// Replace source evidence with owned VT bytes.
    #[must_use]
    pub fn with_vt_bytes(mut self, bytes: Vec<u8>) -> Self {
        self.source = ClientKeySource::Vt { bytes };
        self
    }

    /// Whether native evidence contains a nonzero scan code.
    #[must_use]
    pub fn has_physical_identity(&self) -> bool {
        self.windows_record().and_then(physical_key_id).is_some()
    }

    /// Read native evidence only when the source is a Windows record.
    #[must_use]
    pub fn windows_record(&self) -> Option<WindowsKeyRecord> {
        match self.source {
            ClientKeySource::WindowsConsole { record } => Some(record),
            _ => None,
        }
    }

    /// Resolve physical identity without changing semantic code.
    #[must_use]
    pub fn identity(&self) -> KeyIdentity {
        self.windows_record().and_then(physical_key_id).map_or_else(
            || KeyIdentity::Semantic(self.code.clone()),
            KeyIdentity::Physical,
        )
    }
}

/// Keyboard reporting protocol selected by terminal flags.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyboardProtocol {
    /// Conventional escape sequences.
    Legacy,
    /// Extended keyboard reporting.
    Kitty {
        /// Flags retained exactly as supplied.
        flags: u16,
    },
}

impl KeyboardProtocol {
    /// Whether extended reporting includes key event types.
    #[must_use]
    pub fn reports_event_types(self) -> bool {
        matches!(self, Self::Kitty { flags } if flags & 2 != 0)
    }

    /// Whether extended reporting includes all keys.
    #[must_use]
    pub fn reports_all_keys(self) -> bool {
        matches!(self, Self::Kitty { flags } if flags & 8 != 0)
    }

    /// Select legacy for zero flags, otherwise retain the extended flags.
    #[must_use]
    pub fn from_kitty_flags(flags: u16) -> Self {
        if flags == 0 {
            Self::Legacy
        } else {
            Self::Kitty { flags }
        }
    }
}

impl From<TerminalKey> for ClientInputEvent {
    fn from(key: TerminalKey) -> Self {
        Self::Key {
            code: key.code,
            modifiers: key.modifiers,
            kind: key.kind,
            repeat_count: key.repeat_count,
            generated_text: key.generated_text,
            source: key.source,
        }
    }
}

impl TryFrom<ClientInputEvent> for TerminalKey {
    type Error = ClientInputEvent;

    fn try_from(event: ClientInputEvent) -> Result<Self, Self::Error> {
        let ClientInputEvent::Key {
            code,
            modifiers,
            kind,
            repeat_count,
            generated_text,
            source,
        } = event
        else {
            return Err(event);
        };
        let key = Self::new(code, modifiers & 0x3f).with_generated_text(generated_text);
        let key = match source {
            ClientKeySource::Synthesized => key,
            ClientKeySource::Vt { bytes } => key.with_vt_bytes(bytes),
            ClientKeySource::WindowsConsole { record } => key.with_windows_record(record),
        };
        Ok(key.with_repeat_count(repeat_count).with_kind(kind))
    }
}

/// Host modifyOtherKeys reporting level.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ModifyOtherKeysMode {
    /// Report modified keys that would otherwise be ambiguous.
    Mode1,
    /// Report all modified keys.
    Mode2,
}

impl ModifyOtherKeysMode {
    /// Escape sequence that enables this reporting level.
    #[must_use]
    pub fn set_sequence(self) -> &'static [u8] {
        match self {
            Self::Mode1 => b"\x1b[>4;1m",
            Self::Mode2 => b"\x1b[>4;2m",
        }
    }
}

/// Mouse events requested by the pane program.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MouseProtocolMode {
    /// No mouse reporting.
    None,
    /// Button presses only.
    Press,
    /// Button presses and releases.
    PressRelease,
    /// Motion while a button is down.
    ButtonMotion,
    /// Every mouse movement.
    AnyMotion,
}

/// Mouse coordinate encoding requested by the pane program.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MouseProtocolEncoding {
    /// Conventional byte encoding.
    Default,
    /// UTF-8 coordinates.
    Utf8,
    /// SGR cell coordinates.
    Sgr,
    /// SGR pixel coordinates.
    SgrPixels,
}

/// Owned committed text, separate from a key's semantic code.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TextCommit {
    /// Committed Unicode text.
    text: String,
}

impl TextCommit {
    /// Own the supplied text.
    #[must_use]
    pub fn new(text: impl Into<String>) -> Self {
        Self { text: text.into() }
    }

    /// Borrow the committed text.
    #[must_use]
    pub fn as_str(&self) -> &str {
        &self.text
    }

    /// Transfer ownership of the committed text.
    #[must_use]
    pub fn into_string(self) -> String {
        self.text
    }
}
